/**
 * Writes the generated inputs of the animation:
 * - src/generated/data.js: every number, from the real aggregation code.
 * - src/generated/today-card.png: the real Today card, from the real renderer and CSS.
 */
import { mkdirSync } from 'node:fs'
import { dashboardDocument, explainerData } from '../product/synthetic-day.ts'
import { launchChromium } from './browser.ts'

const root = new URL('..', import.meta.url).pathname
const generated = `${root}src/generated`
mkdirSync(generated, { recursive: true })

const data = explainerData()
await Bun.write(`${generated}/data.js`, `// Generated by scripts/prepare.ts. Do not edit.\nexport const data = ${JSON.stringify(data, null, '\t')}\n`)

const css = await Bun.file(new URL('../../../service/dashboard/dashboard.css', import.meta.url)).text()
const html = dashboardDocument()
	.replace('<link rel="stylesheet" href="/assets/dashboard.css">', `<style>${css}</style>`)
	.replace(/<script[\s\S]*?<\/script>/g, '')
	.replace('</head>', '<style>html,body,section,.hero{background:transparent!important}</style></head>')

const browser = await launchChromium()
const page = await browser.newPage({ viewport: { width: 1100, height: 900 }, deviceScaleFactor: 3, colorScheme: 'light' })
await page.setContent(html, { waitUntil: 'load' })
const card = page.locator('.hero .verdict').first()
const label = (await card.locator('.verdict-label').innerText()).replace(/\s+/g, ' ').trim()
const figure = await card.locator('.verdict-figure').innerText()
const caption = await card.locator('.verdict-caption').innerText()
const box = await card.boundingBox()
if (!box) throw new Error('The Today card is not visible')
// Pad the crop so the card's hard offset shadow is kept.
await page.screenshot({
	path: `${generated}/today-card.png`,
	omitBackground: true,
	clip: { x: box.x - 4, y: box.y - 4, width: box.width + 14, height: box.height + 14 },
})
await browser.close()

// The screenshot must say what the data says.
const hours = Math.floor(data.today.worked_minutes / 60)
const expected = `${hours}h ${data.today.worked_minutes % 60}m`
if (figure !== expected || !label.includes(data.today.status)) {
	throw new Error(`Card shows "${label} ${figure}", expected ${data.today.status} ${expected}`)
}
console.log(`Today card: ${label} · ${figure} · ${caption} · ${box.width}×${box.height} CSS px`)
