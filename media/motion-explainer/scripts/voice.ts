/**
 * Generates the narration: one Kokoro clip per line, then the mix.
 *
 *   bun media/motion-explainer/scripts/voice.ts
 *
 * Writes out/voice/*.wav, src/generated/narration.js (clip durations, which
 * stretch caption holds when speech needs more time), and narration.m4a.
 *
 * VOICE_PYTHON: a Python with kokoro-onnx and soundfile. Default: ~/.cache/cukup-voice/.venv/bin/python
 * KOKORO_DIR: holds kokoro-v1.0.onnx and voices-v1.0.bin. Default: ~/.cache/cukup-voice
 */
import { mkdirSync, rmSync } from 'node:fs'
import { homedir } from 'node:os'
import { endCard, endKey, lineKey, scenes } from '../src/scenes.js'

const root = new URL('..', import.meta.url).pathname
const voiceDir = `${root}out/voice`
rmSync(voiceDir, { recursive: true, force: true })
mkdirSync(voiceDir, { recursive: true })

const lines = [
	...scenes.flatMap((scene) =>
		scene.lines.map((line, index) => ({ key: lineKey(scene.id, index), text: line.say ?? line.text })),
	),
	{ key: endKey, text: endCard.say },
]
await Bun.write(`${voiceDir}/lines.json`, JSON.stringify(lines, null, '\t'))

const cache = `${homedir()}/.cache/cukup-voice`
const python = process.env.VOICE_PYTHON ?? `${cache}/.venv/bin/python`
const synth = Bun.spawn([python, `${root}scripts/voice.py`, `${voiceDir}/lines.json`, voiceDir], {
	env: { ...process.env, KOKORO_DIR: process.env.KOKORO_DIR ?? cache },
	stdout: 'pipe',
	stderr: 'inherit',
})
const output = await new Response(synth.stdout).text()
if ((await synth.exited) !== 0) throw new Error('Speech synthesis failed')
const narration = JSON.parse(output.trim().split('\n').at(-1)!)

await Bun.write(
	`${root}src/generated/narration.js`,
	`// Generated by scripts/voice.ts. Do not edit.\nexport const narration = ${JSON.stringify(narration, null, '\t')}\n`,
)
console.log(`Synthesized ${lines.length} clips with ${narration.voice} at speed ${narration.speed}`)

// Mix in a fresh process, so the timeline reads the new durations.
const mix = Bun.spawn(['bun', `${root}scripts/mix.ts`], { stdout: 'inherit', stderr: 'inherit' })
if ((await mix.exited) !== 0) throw new Error('Mix failed')
